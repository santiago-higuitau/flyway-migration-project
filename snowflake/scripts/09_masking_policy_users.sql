USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_LIBRARY;
USE DATABASE LIBRARY_DW;
USE SCHEMA RAW;

CREATE OR REPLACE MASKING POLICY mask_phone AS (val STRING) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() = 'ROLE_DATA_ENGINEER' THEN val
        WHEN CURRENT_ROLE() = 'ROLE_DATA_ANALYST'  THEN CONCAT(LEFT(val, 6), '-****')
        ELSE '***-***-****'
    END;

CREATE OR REPLACE MASKING POLICY mask_email AS (val STRING) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() = 'ROLE_DATA_ENGINEER' THEN val
        ELSE '*** email protegido ***'
    END;

ALTER TABLE USERS MODIFY COLUMN phone SET MASKING POLICY mask_phone;
ALTER TABLE USERS MODIFY COLUMN email SET MASKING POLICY mask_email;

-- Verificar que las politicas quedaron atadas
SHOW MASKING POLICIES;

SELECT *
FROM TABLE(INFORMATION_SCHEMA.POLICY_REFERENCES(
    REF_ENTITY_NAME => 'LIBRARY_DW.RAW.USERS',
    REF_ENTITY_DOMAIN => 'TABLE'
));

